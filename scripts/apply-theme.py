#!/usr/bin/env python3
# Carry the current qtile theme over to the terminal and rofi. qtile runs this
# on every start and reload, so changing "theme" in config.json is all it takes.
#
#   ghostty  ~/.config/ghostty/qtile.conf, included by the ghostty config. A
#            theme can name the ghostty theme it belongs with under "terminal";
#            without one, the sixteen terminal colours are picked out of the
#            theme's own by hue. Either way the background is the bar's, so the
#            two sit together. Fish uses named colours, so it follows along.
#   rofi     ~/.config/rofi/qtile.rasi, which config.rasi loads: the palette
#            file ~/.config/rofi/<theme>.rasi if there is one, otherwise a
#            palette made from the theme's colours over rofi/layout.rasi.
#
# The login screen is installed as root, so it is not done here - run
# `sudo ~/.config/sddm/install.sh` after switching to bring it along.
import colorsys
import json
import subprocess
from os import path

home = path.expanduser("~")
qtile_path = path.join(home, ".config", "qtile")
ghostty_output = path.join(home, ".config", "ghostty", "qtile.conf")
rofi_path = path.join(home, ".config", "rofi")


def load_theme():
    config_file = path.join(qtile_path, "config.json")
    if not path.isfile(config_file):
        config_file = path.join(qtile_path, "default-config.json")

    with open(config_file) as f:
        name = json.load(f)["theme"]

    with open(path.join(qtile_path, "themes", f"{name}.json")) as f:
        return name, json.load(f)


def colour(theme, key):
    value = theme[key]
    return value[0] if isinstance(value, list) else value


def mix(a, b, amount):
    a, b = (bytes.fromhex(c.lstrip("#")) for c in (a, b))
    return "#" + bytes(round(x + (y - x) * amount) for x, y in zip(a, b)).hex()


def hue_palette(theme):
    """The terminal's sixteen colours, taken from whichever of the theme's
    colours lie closest in hue to red, green, yellow, blue, magenta and cyan."""
    candidates = {
        colour(theme, key)
        for key in theme
        if key.startswith("color") or key in ("urgent", "active", "focus")
    }

    def rgb(c):
        return [x / 255 for x in bytes.fromhex(c.lstrip("#"))]

    # Greys and near-whites have no hue worth matching on.
    candidates = [c for c in candidates if max(rgb(c)) - min(rgb(c)) > 0.1] or list(
        candidates
    )

    def nearest(target):
        def distance(c):
            d = abs(colorsys.rgb_to_hsv(*rgb(c))[0] * 360 - target)
            return min(d, 360 - d)

        return min(candidates, key=distance)

    dark, light = colour(theme, "dark"), colour(theme, "light")
    hues = [nearest(h) for h in (0, 120, 50, 220, 300, 180)]
    normal = [colour(theme, "inactive"), *hues, mix(light, dark, 0.15)]
    bright = [mix(light, dark, 0.55), *hues, light]
    return normal + bright


def ghostty_config(name, theme):
    dark, light = colour(theme, "dark"), colour(theme, "light")
    lines = [f"# Generated by qtile/scripts/apply-theme.py from themes/{name}.json"]

    if "terminal" in theme:
        lines.append(f"theme = {theme['terminal']}")
    else:
        lines += [f"palette = {i}={c}" for i, c in enumerate(hue_palette(theme))]
        lines += [
            f"foreground = {light}",
            f"cursor-color = {light}",
            f"cursor-text = {dark}",
            f"selection-background = {mix(dark, light, 0.25)}",
            f"selection-foreground = {light}",
        ]

    lines.append(f"background = {dark}")
    return "\n".join(lines) + "\n"


def rofi_config(name, theme):
    header = f"/* Generated by qtile/scripts/apply-theme.py from themes/{name}.json */\n"
    palette_file = path.join(rofi_path, f"{name}.rasi")
    if path.isfile(palette_file):
        return header + f'@import "{palette_file}"\n'

    dark, light = colour(theme, "dark"), colour(theme, "light")
    variables = {
        "ground": dark,
        "panel": dark + "e6",
        "surface": colour(theme, "focus"),
        "line": colour(theme, "inactive"),
        "edge": mix(dark, light, 0.15),
        "ash": mix(dark, light, 0.3),
        "muted": mix(dark, light, 0.45),
        "fg": light,
        "accent": colour(theme, "active"),
        "info": colour(theme, "color1"),
        "alert": colour(theme, "urgent"),
        "note": colour(theme, "color4"),
    }
    lines = [header, "* {"]
    lines += [f"    {key}: {value};" for key, value in variables.items()]
    lines += [
        "}",
        "",
        f'@import "{path.join(rofi_path, "layout.rasi")}"',
        "",
        f"element-text {{ highlight: bold {colour(theme, 'color4')}; }}",
        f"element selected.normal element-text {{ highlight: bold {dark}; }}",
    ]
    return "\n".join(lines) + "\n"


def write(file, content):
    """Write the file if it changed; say whether it did."""
    try:
        with open(file) as f:
            if f.read() == content:
                return False
    except FileNotFoundError:
        pass

    with open(file, "w") as f:
        f.write(content)
    return True


def main():
    name, theme = load_theme()

    # rofi reads its theme every time it opens, so this needs no reload.
    write(path.join(rofi_path, "qtile.rasi"), rofi_config(name, theme))

    if write(ghostty_output, ghostty_config(name, theme)):
        # ghostty reloads its config on SIGUSR2; open windows recolour too.
        subprocess.run(["pkill", "-USR2", "-x", "ghostty"])


if __name__ == "__main__":
    main()
